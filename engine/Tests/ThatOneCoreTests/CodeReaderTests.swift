import XCTest
@testable import ThatOneCore

final class CodeReaderTests: XCTestCase {
    @discardableResult @nonobjc
    func write(_ data: Data, _ name: String, in dir: URL) -> URL {
        let url = dir.appendingPathComponent(name)
        try! FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try! data.write(to: url)
        return URL(fileURLWithPath: RealPath.of(url.path))
    }
    @nonobjc func write(_ text: String, _ name: String, in dir: URL) -> URL { write(Data(text.utf8), name, in: dir) }
    func anchor(_ s: ReadSegment) -> [String: Any] { try! JSONSerialization.jsonObject(with: Data(s.anchor.utf8)) as! [String: Any] }
    func failure(_ body: () throws -> ReadResult) -> ReadFailure? {
        do { _ = try body(); return nil } catch { return error as? ReadFailure }
    }

    func testChunksCarryLineAnchorsSymbolAndAHeader() throws {
        let root = TestSupport.tempDir("repo")
        let url = write(CodeIndexingTests.source, "Sources/Net/Retry.swift", in: root)
        let result = try CodeReader(roots: { [root.path] }).read(url)
        XCTAssertEqual(result.segments.count, 2)
        let fn = result.segments[1]
        XCTAssertEqual(fn.modality, "text")
        XCTAssertEqual(anchor(fn)["line0"] as? Int, 3)
        XCTAssertEqual(anchor(fn)["line1"] as? Int, 14)
        XCTAssertEqual(anchor(fn)["symbol"] as? String, "retryWithBackoff")
        XCTAssertEqual(fn.text.components(separatedBy: "\n").first, "Sources/Net/Retry.swift · retryWithBackoff · L3–14")
        XCTAssertTrue(fn.text.contains("delay *= 2"))
        XCTAssertEqual(result.segments[0].text.components(separatedBy: "\n").first, "Sources/Net/Retry.swift · lines 1–2 · L1–2")
        XCTAssertNil(anchor(result.segments[0])["symbol"])
        XCTAssertTrue(result.gateText.contains("import Foundation"))
    }

    func testOutsideAnyWatchedFolderTheHeaderUsesTheFileName() throws {
        let url = write(CodeIndexingTests.source, "x/Retry.swift", in: TestSupport.tempDir("loose"))
        XCTAssertTrue(try CodeReader().read(url).segments[1].text.hasPrefix("Retry.swift · retryWithBackoff · L3–14\n"))
    }

    func testCRLFAndLoneCRGiveTheSameLineNumbersAsLF() throws {
        let root = TestSupport.tempDir("repo")
        let reader = CodeReader(roots: { [root.path] })
        let lf = try reader.read(write(CodeIndexingTests.source, "a.swift", in: root))
        let crlf = try reader.read(write(CodeIndexingTests.source.replacingOccurrences(of: "\n", with: "\r\n"), "b.swift", in: root))
        let cr = try reader.read(write(CodeIndexingTests.source.replacingOccurrences(of: "\n", with: "\r"), "c.swift", in: root))
        XCTAssertEqual(lf.segments.map { $0.anchor }, crlf.segments.map { $0.anchor })
        XCTAssertEqual(lf.segments.map { $0.anchor }, cr.segments.map { $0.anchor })
        XCTAssertFalse(crlf.segments.contains { $0.text.contains("\r") })
    }

    func testSkippedFilesSayWhy() {
        let dir = TestSupport.tempDir("skip")
        let reader = CodeReader()
        XCTAssertEqual(failure { try reader.read(write("var a=1\n", "app.min.js", in: dir)) }, .empty("minified"))
        XCTAssertEqual(failure { try reader.read(write("// Code generated by x. DO NOT EDIT.\npackage a\n", "a.go", in: dir)) }, .empty("generated"))
        XCTAssertEqual(failure { try reader.read(write(Data([0x7F, 0x45, 0x4C, 0x46, 0x00, 0x01]), "tool.sh", in: dir)) }, .empty("not a text file"))
        XCTAssertEqual(failure { try reader.read(write(String(repeating: "let a = 1\n", count: 100_001), "big.swift", in: dir)) },
                       .tooLarge("larger than 1 MB"))
        XCTAssertEqual(failure { try reader.read(write("\n\n   \n", "blank.py", in: dir)) }, .empty("no code"))
        XCTAssertEqual(failure { try reader.read(URL(fileURLWithPath: dir.path + "/gone.swift")) }, .empty("not a text file"))
    }

    func testTheReaderIsRegisteredForCode() {
        XCTAssertTrue(Indexer.makeReaders(ocr: { _ in "" }, transcriber: nil, shouldContinue: { true })["code"] is CodeReader)
    }

    func testGateTextIsTheWholeNormalisedFile() throws {
        let root = TestSupport.tempDir("repo")
        let crlf = CodeIndexingTests.source.replacingOccurrences(of: "\n", with: "\r\n")
        let result = try CodeReader(roots: { [root.path] }).read(write(crlf, "a.swift", in: root))
        XCTAssertEqual(result.gateText, "\n" + CodeRules.lines(CodeIndexingTests.source).joined(separator: "\n"))
        XCTAssertFalse(result.gateText.contains("\r"))
    }

    func testMostlyInvalidUTF8IsNotATextFile() {
        let dir = TestSupport.tempDir("skip")
        XCTAssertEqual(failure { try CodeReader().read(write(Data(repeating: 0xFF, count: 400), "bad.ts", in: dir)) }, .empty("not a text file"))
    }

    func testAFileThatGrewPastTheLimitAfterTheStatIsTooLarge() {
        // The reader maps this branch to .tooLarge; inspect is what reports it.
        XCTAssertEqual(CodeRules.inspect(name: "a.swift", data: Data(repeating: 0x61, count: Int(CodeRules.maxBytes) + 1)), .skip("too large"))
    }
}
