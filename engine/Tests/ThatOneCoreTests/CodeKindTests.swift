import XCTest
@testable import ThatOneCore

final class CodeKindTests: XCTestCase {
    func skip(_ text: String, _ name: String = "a.ts") -> String? { CodeRules.skipReason(name: name, data: Data(text.utf8)) }

    func testCodeExtensionsAreDetectedOffByDefaultAndHidden() {
        for ext in ["swift", "ts", "tsx", "js", "jsx", "mjs", "cjs", "mts", "py", "go", "rs", "java", "kt", "c", "h", "cc",
                    "cpp", "hpp", "m", "mm", "rb", "php", "sh", "bash", "zsh", "sql", "lua", "scala", "cs"] {
            XCTAssertEqual(Kinds.detect("/r/a.\(ext.uppercased())"), "code", ext)
        }
        for name in ["README.md", "notes.txt", "page.html", "package.json", "a.yaml", "Cargo.toml", "yarn.lock", "Makefile"] {
            XCTAssertNotEqual(Kinds.detect("/r/" + name), "code", name)
        }
        XCTAssertFalse(Kinds.defaultEnabled.contains("code"))
        XCTAssertEqual(Kinds.hiddenByDefault, ["code"])
        XCTAssertEqual(Kinds.all, ["image", "pdf", "document", "text", "audio", "video", "code"])
        XCTAssertEqual(Kinds.extensions(of: "code"), Kinds.codeExtensions)
    }

    func testConfigKeepsCodeAndOldConfigsLeaveItOff() throws {
        let url = TestSupport.tempDir().appendingPathComponent("config.json")
        try Config(kinds: ["code", "pdf"]).save(to: url)
        XCTAssertEqual(try Config.load(from: url).kinds, ["code", "pdf"])
        try Data("{}".utf8).write(to: url)
        XCTAssertFalse(try Config.load(from: url).kinds.contains("code"))
    }

    func testPlainSourceIsRead() {
        XCTAssertNil(skip("export function f() {\n  return 1\n}\n"))
    }

    func testMinifiedByName() {
        for name in ["app.min.js", "x.MIN.mjs", "vendor.bundle.js"] { XCTAssertEqual(skip("var a=1\n", name), "minified", name) }
        XCTAssertNil(skip("var a=1\n", "minimal.js"))
    }

    func testMinifiedByLineLength() {
        XCTAssertEqual(skip("x\n" + String(repeating: "a", count: 5_001) + "\n", "a.js"), "minified")
        XCTAssertEqual(skip(Array(repeating: String(repeating: "b", count: 400), count: 10).joined(separator: "\n"), "a.js"), "minified")
        XCTAssertNil(skip(Array(repeating: String(repeating: "c", count: 300), count: 10).joined(separator: "\n"), "a.js"))
    }

    func testGeneratedMarkerOnlyInTheFirstFiveLines() {
        XCTAssertEqual(skip("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", "a.go"), "generated")
        XCTAssertEqual(skip("#!/bin/sh\n\n\n\n# @generated by a tool\necho hi\n", "a.sh"), "generated")
        XCTAssertNil(skip("1\n2\n3\n4\n5\n// DO NOT EDIT below this line\n"))
    }

    func testBinaryAndNonUTF8AreNotText() {
        XCTAssertEqual(CodeRules.skipReason(name: "a.c", data: Data([0x69, 0x6E, 0x74, 0x00, 0x20])), "not a text file")
        XCTAssertEqual(CodeRules.skipReason(name: "a.c", data: Data(repeating: 0xFF, count: 400)), "not a text file")
    }

    func testOverOneMegabyteIsTooLarge() {
        XCTAssertEqual(skip(String(repeating: "let a = 1\n", count: 100_001), "big.swift"), "too large")
    }

    func testLinesNormaliseCRLFAndLoneCR() {
        XCTAssertEqual(CodeRules.lines("a\r\nb\rc\n"), ["a", "b", "c"])
        XCTAssertEqual(CodeRules.lines("a\n\nb"), ["a", "", "b"])
        XCTAssertEqual(CodeRules.lines(""), [])
    }

    func testDecodeStripsTheBOMAndToleratesAFewBadBytes() {
        XCTAssertEqual(CodeRules.decode(Data([0xEF, 0xBB, 0xBF]) + Data("x".utf8)), "x")
        var mostlyFine = Data(String(repeating: "let value = 1\n", count: 20).utf8)
        mostlyFine.append(0xE9)                                     // one Latin-1 byte in a comment
        XCTAssertNotNil(CodeRules.decode(mostlyFine))
        XCTAssertNil(CodeRules.decode(Data(repeating: 0xFE, count: 100)))
    }
}
