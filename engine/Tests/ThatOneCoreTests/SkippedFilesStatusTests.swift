import XCTest
@testable import ThatOneCore

/// `thatone status` lists skipped files with their reasons (M5 acceptance item 49), never as failed.
final class SkippedFilesStatusTests: XCTestCase {
    static let reasons = ["too large", "minified", "generated", "not a text file", "secret"]

    func makeEngine() throws -> Engine { try CodeIndexingTests.makeEngine() }

    /// `count` skipped files cycling through the reasons, named so that path order differs from insertion order.
    func seedSkipped(_ e: Engine, count: Int) throws {
        for n in (0..<count).reversed() {
            try e.store.upsertFile(path: String(format: "/repo/f%03d.ts", n), contentId: nil, kind: "code", size: 1, mtime: 1,
                                   status: "skipped", note: Self.reasons[n % Self.reasons.count])
        }
        try e.store.upsertFile(path: "/repo/bad.png", contentId: nil, kind: "image", size: 1, mtime: 1, status: "failed", note: "cannot decode")
    }

    func status(_ e: Engine, json: Bool = false) throws -> [String] {
        var out: [String] = []
        try CLI.status(json ? ["--json"] : [], { LocalEngineService(engine: e) }, { nil }, { out.append($0) })
        return out
    }

    func testTheStoreListsSkippedFilesByPathWithTheirReasonAndCounts() throws {
        let e = try makeEngine()
        try seedSkipped(e, count: 7)
        let listed = try e.store.skippedFiles(limit: 5)
        XCTAssertEqual(listed.total, 7)
        XCTAssertEqual(listed.files.map { "\($0.path)|\($0.note)" },
                       ["/repo/f000.ts|too large", "/repo/f001.ts|minified", "/repo/f002.ts|generated",
                        "/repo/f003.ts|not a text file", "/repo/f004.ts|secret"])
    }

    func testStatusTextListsSkippedFilesWithReasonsCappedAtTwenty() throws {
        let e = try makeEngine()
        try seedSkipped(e, count: 23)
        let out = try status(e)
        let header = try XCTUnwrap(out.firstIndex(of: "skipped files:"), "\(out)")
        let listed = Array(out[(header + 1)...])
        XCTAssertEqual(listed.count, 21, "\(listed)")
        XCTAssertEqual(listed.first, "  /repo/f000.ts  too large")
        XCTAssertEqual(listed[3], "  /repo/f003.ts  not a text file")
        XCTAssertEqual(listed[19], "  /repo/f019.ts  secret")
        XCTAssertEqual(listed.last, "  (+3 more)")
        XCTAssertTrue(out.contains("  could not read: /repo/bad.png: cannot decode"))
        XCTAssertFalse(out.contains { $0.contains("could not read: /repo/f0") })          // skipped is never failed
    }

    func testStatusTextHasNoMoreLineAtExactlyTwenty() throws {
        let e = try makeEngine()
        try seedSkipped(e, count: 20)
        let out = try status(e)
        XCTAssertEqual(out.last, "  /repo/f019.ts  secret")
        XCTAssertFalse(out.contains { $0.contains("more)") })
    }

    func testStatusJSONHasTheSkippedFilesCappedAtTwoHundredWithATotal() throws {
        let e = try makeEngine()
        try seedSkipped(e, count: 205)
        let report = try JSONSerialization.jsonObject(with: Data(try status(e, json: true).joined(separator: "\n").utf8)) as! [String: Any]
        let skipped = try XCTUnwrap(report["skippedFiles"] as? [[String: String]])
        XCTAssertEqual(skipped.count, 200)
        XCTAssertEqual(skipped.first, ["path": "/repo/f000.ts", "note": "too large"])
        XCTAssertEqual(report["skippedFilesTotal"] as? Int, 205)
        XCTAssertEqual((report["failedFiles"] as? [[String: String]])?.map { $0["path"] }, ["/repo/bad.png"])
    }

    func testNoSkippedFilesAddsNoLines() throws {
        let e = try makeEngine()
        let before = try status(e)
        XCTAssertFalse(before.contains { $0.contains("skipped") }, "\(before)")
        XCTAssertEqual(before.count, 4, "\(before)")                       // folders, files, segments, queue: as before
        let report = try JSONSerialization.jsonObject(with: Data(try status(e, json: true).joined(separator: "\n").utf8)) as! [String: Any]
        XCTAssertEqual(report["skippedFiles"] as? [[String: String]], [])
        XCTAssertEqual(report["skippedFilesTotal"] as? Int, 0)
    }

    func testIndexedCodeSkipsShowUpInStatusAsSkippedNeverFailed() throws {
        let repo = TestSupport.tempDir("repo")
        CodeIndexingTests.write("var a=1\n", "web/app.min.js", in: repo)
        CodeIndexingTests.write(String(repeating: "let a = 1\n", count: 100_001), "big.swift", in: repo)
        CodeIndexingTests.write("// Code generated by protoc. DO NOT EDIT.\npackage pb\n", "pb/gen.go", in: repo)
        let e = try makeEngine()
        try CodeIndexingTests.indexAll(e, repo)
        let real = RealPath.of(repo.path)
        let out = try status(e)
        XCTAssertTrue(out.contains("skipped files:"), "\(out)")
        for (name, reason) in [("big.swift", "too large"), ("pb/gen.go", "generated"), ("web/app.min.js", "minified")] {
            XCTAssertTrue(out.contains("  \(real)/\(name)  \(reason)"), "\(name): \(out)")
        }
        XCTAssertFalse(out.contains { $0.contains("could not read") }, "\(out)")
    }

    func testTheServiceStatusCarriesSkippedFilesAndOlderPayloadsStillDecode() throws {
        let e = try makeEngine()
        try seedSkipped(e, count: 3)
        let s = try LocalEngineService(engine: e).status()
        XCTAssertEqual(s.skippedFiles.map(\.path), ["/repo/f000.ts", "/repo/f001.ts", "/repo/f002.ts"])
        XCTAssertEqual(s.skippedFilesTotal, 3)
        let round = try JSONDecoder().decode(ServiceStatus.self, from: JSONEncoder().encode(s))
        XCTAssertEqual(round, s)
        let old = #"{"state":"idle","detail":"","folders":[],"files":{},"segments":{},"queue":{"queued":0,"running":0,"failed":0},"failedFiles":[]}"#
        let decoded = try JSONDecoder().decode(ServiceStatus.self, from: Data(old.utf8))
        XCTAssertEqual(decoded.skippedFiles, [])
        XCTAssertEqual(decoded.skippedFilesTotal, 0)
    }
}
