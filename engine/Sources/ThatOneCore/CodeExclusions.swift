import Foundation

/// What makes a code file not worth reading, judged from its name and bytes (spec M5 "Skipped files").
public enum CodeRules {
    public static let maxBytes: Int64 = 1_000_000
    public static let maxAverageLineLength = 300.0
    public static let maxLineLength = 5_000
    public static let minifiedSuffixes = [".min.js", ".min.mjs", ".bundle.js"]
    public static let generatedMarkers = ["@generated", "DO NOT EDIT", "Code generated by"]
    static let headerLines = 5
    static let binaryProbeBytes = 8192
    /// A lossy decode with more than this share of replacement characters is not text.
    static let maxInvalidShare = 0.05

    /// Why a code file is skipped ("too large", "minified", "generated", "not a text file"); nil when it is read.
    public static func skipReason(name: String, data: Data) -> String? {
        if case .skip(let reason) = inspect(name: name, data: data) { return reason }
        return nil
    }

    /// The outcome of looking at a code file once: skipped with a reason, or the lines (decoded and split once) to chunk.
    public enum Inspection: Equatable {
        case skip(String)
        case lines([String])
    }

    /// Decodes and splits the file a single time; `skipReason` and the reader both go through here.
    public static func inspect(name: String, data: Data) -> Inspection {
        if Int64(data.count) > maxBytes { return .skip("too large") }
        let lower = name.lowercased()
        if minifiedSuffixes.contains(where: { lower.hasSuffix($0) }) { return .skip("minified") }
        if data.prefix(binaryProbeBytes).contains(0) { return .skip("not a text file") }
        guard let text = decode(data) else { return .skip("not a text file") }
        let all = lines(text)
        if all.prefix(headerLines).contains(where: { line in generatedMarkers.contains { line.contains($0) } }) { return .skip("generated") }
        var total = 0
        for line in all {
            let n = line.unicodeScalars.count
            if n > maxLineLength { return .skip("minified") }
            total += n
        }
        if !all.isEmpty, Double(total) / Double(all.count) > maxAverageLineLength { return .skip("minified") }
        return .lines(all)
    }

    /// UTF-8 without a BOM; a few bad bytes become U+FFFD, a file that is mostly invalid is not text (nil).
    public static func decode(_ data: Data) -> String? {
        let bytes = data.starts(with: [0xEF, 0xBB, 0xBF]) ? Data(data.dropFirst(3)) : data
        if let exact = String(data: bytes, encoding: .utf8) { return exact }
        let lossy = String(decoding: bytes, as: UTF8.self)
        let scalars = lossy.unicodeScalars
        let bad = scalars.filter { $0 == "\u{FFFD}" }.count
        return scalars.isEmpty || Double(bad) / Double(scalars.count) > maxInvalidShare ? nil : lossy
    }

    /// Lines as an editor numbers them: CRLF and lone CR count as one break, a final newline adds no line.
    public static func lines(_ text: String) -> [String] {
        let normalized = text.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        var parts = normalized.components(separatedBy: "\n")
        if parts.last == "" { parts.removeLast() }
        return parts
    }
}

/// Code files left out before they are read: build folders and `.gitignore` rules. Applies to the `code` kind only;
/// other kinds inside a repository index exactly as before. Safe to share between threads.
public final class CodeExclusions {
    public static let buildFolderNames: Set<String> = ["build", "dist", "target", ".next", "DerivedData", "Pods", "vendor",
                                                       ".build", "out", "coverage"]
    private let loader: GitIgnoreLoader

    public init(loader: GitIgnoreLoader = GitIgnoreLoader()) { self.loader = loader }

    /// A matcher for one scan of `root` (it remembers folders it has judged).
    public func stack(forRoot root: String) -> GitIgnoreStack { GitIgnoreStack(root: root, loader: loader) }

    /// Why the code file at `path` is left out ("build folder", "ignored by .gitignore"); nil when it is read.
    /// `root` is the watched folder holding it; without one, the nearest enclosing git work tree (or the file's folder).
    public func reason(path: String, root: String?, stack: GitIgnoreStack? = nil) -> String? {
        let base = Self.effectiveRoot(path: path, watchedRoot: root)
        let prefix = base == "/" ? "/" : base + "/"
        guard path.hasPrefix(prefix) else { return nil }
        let relative = String(path.dropFirst(prefix.count))
        if relative.split(separator: "/").dropLast().contains(where: { Self.buildFolderNames.contains(String($0)) }) {
            return "build folder"
        }
        let ignore = stack.flatMap { $0.root == base ? $0 : nil } ?? self.stack(forRoot: base)
        return ignore.isIgnored(relative, isDirectory: false) ? "ignored by .gitignore" : nil
    }

    public static func effectiveRoot(path: String, watchedRoot: String?) -> String {
        if let watchedRoot { return watchedRoot.count > 1 && watchedRoot.hasSuffix("/") ? String(watchedRoot.dropLast()) : watchedRoot }
        let start = (path as NSString).deletingLastPathComponent
        var folder = start
        while folder != "/" && !folder.isEmpty {
            if FileManager.default.fileExists(atPath: folder + "/.git") { return folder }
            folder = (folder as NSString).deletingLastPathComponent
        }
        return start
    }
}
